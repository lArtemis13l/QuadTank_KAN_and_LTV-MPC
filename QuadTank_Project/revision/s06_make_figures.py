def fig_degradation():
    s = json.load(open(os.path.join(RES, "scenarios.json")))
    fig, axes = plt.subplots(1, 2, figsize=(7.0, 2.3))
    for ax, reg in zip(axes, ("MP", "NMP")):
        sw = s[reg]["S4_degradation"]["sweep"]
        for n in KEY:
            if n not in sw:
                continue
            xs = [r["degradation"] * 100 for r in sw[n]]
            ys = [abs(r["ss_err_h1_cm"]) for r in sw[n]]
            ax.plot(xs, ys, "o-", ms=3, label=n, **{k: v for k, v in STYLE[n].items() if k != "ls"},
                    ls=STYLE[n]["ls"])
        ax.set_xlabel("pump-gain degradation (%)")
        ax.set_ylabel(r"$|h_1 - h_1^{\rm ref}|$ at steady state (cm)" if reg == "MP" else "")
        ax.set_title(f"{reg} regime", fontsize=8)
        ax.legend(loc="upper left")
    save(fig, "Fig_DegradationSweep.pdf")


