def fig_roa():
    st = json.load(open(os.path.join(RES, "stability.json")))
    fig, axes = plt.subplots(1, 2, figsize=(7.0, 2.6))
    for ax, reg in zip(axes, ("MP", "NMP")):
        roa = st[reg].get("roa_estimate")
        if roa is None:
            continue
        g = np.array(roa["grid_cm"])
        ok = np.array(roa["converged"], dtype=float)
        ax.pcolormesh(g, g, ok.T, cmap="Greens", vmin=0, vmax=1.4, shading="nearest")
        ax.set_xlabel(r"$h_1(0)$ (cm)")
        ax.set_ylabel(r"$h_2(0)$ (cm)" if reg == "MP" else "")
        ax.set_title(f"{reg}: converged fraction "
                     f"{roa['converged_fraction']*100:.0f}%", fontsize=8)
        ax.grid(False)
    save(fig, "Fig_ROA.pdf")


