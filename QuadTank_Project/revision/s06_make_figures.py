STYLE = {
    "LTV-MPC": dict(color="black", ls="-"),
    "Symbolic KAN": dict(color="crimson", ls="--"),
    "MLP (32-32)": dict(color="tab:blue", ls="-."),
    "MLP (8)": dict(color="tab:cyan", ls=":"),
    "DeepONet": dict(color="tab:green", ls=":"),
    "Poly ridge (deg 2)": dict(color="tab:orange", ls=":"),
    "Poly ridge (deg 3)": dict(color="tab:brown", ls="-."),
    "Gain-scheduled LQR": dict(color="tab:purple", ls=(0, (3, 1, 1, 1))),
}
KEY = ["LTV-MPC", "Symbolic KAN", "MLP (32-32)", "Gain-scheduled LQR", "Poly ridge (deg 3)"]


def save(fig, name):
    for d in (FIGS, PAPER):
        if os.path.isdir(d):
            fig.savefig(os.path.join(d, name), bbox_inches="tight")
    plt.close(fig)
    print("  wrote", name, flush=True)


def slug(n):
    return n.replace(" ", "_").replace("(", "").replace(")", "")


def load_traj(tag, regime, name):
    p = os.path.join(TRAJ, f"{tag}_{regime}_{slug(name)}.npz")
    return np.load(p) if os.path.exists(p) else None


# ------------------------------------------------------------------ Fig A
def fig_tracking(regime="NMP"):
    fig, ax = plt.subplots(3, 1, figsize=(3.5, 4.2), sharex=True)
    for n in KEY:
        d = load_traj("S1", regime, n)
        if d is None:
            continue
        ax[0].plot(d["t"], d["x"][:, 0], label=n, **STYLE[n])
        ax[1].plot(d["t"], d["x"][:, 1], **STYLE[n])
        ax[2].plot(d["t"], d["u"][:, 0], **STYLE[n])
    ref = d["ref"][0]
    ax[0].axhline(ref[0], color="gray", ls=":", lw=0.8)
    ax[1].axhline(ref[1], color="gray", ls=":", lw=0.8)
    ax[0].set_ylabel(r"$h_1$ (cm)")
    ax[1].set_ylabel(r"$h_2$ (cm)")
    ax[2].set_ylabel(r"$u_1$ (V)")
    ax[2].set_xlabel("Time (s)")
    ax[0].legend(ncol=2, frameon=True, loc="upper right")
    fig.subplots_adjust(hspace=0.12)
    save(fig, f"Fig_Track_{regime}.pdf")


# ------------------------------------------------------------------ Fig B
def fig_complexity():
    d = json.load(open(os.path.join(RES, "sparsity_sweep.json")))
    fig, axes = plt.subplots(1, 2, figsize=(7.0, 2.4), sharey=False)
    for ax, reg in zip(axes, ("MP", "NMP")):
        k = d[reg]["kan_support_curve"]
        p = d[reg]["direct_polynomial_curve"]
        ax.plot([c["flops"] for c in k], [c["nmae"] for c in k], "o-",
                color="crimson", ms=3, label="KAN-selected support")
        ax.plot([c["flops"] for c in p], [c["nmae"] for c in p], "s--",
                color="tab:blue", ms=3, label="direct sparse polynomial (OMP)")
        dep = d[reg]["deployed"]
        ax.plot([dep["flops"]], [dep["nmae"]], "*", color="k", ms=11,
                label=f"deployed ({dep['k']} terms)")
        ax.set_xscale("log")
        ax.set_xlabel("multiply–accumulate operations per call")
        ax.set_ylabel("policy imitation nMAE (% of 12 V)" if reg == "MP" else "")
        ax.set_title(f"{reg} regime", fontsize=8)
        ax.legend(loc="upper right")
    save(fig, "Fig_Complexity.pdf")


