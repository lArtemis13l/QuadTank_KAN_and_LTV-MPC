def fig_signflip():
    a = json.load(open(os.path.join(RES, "signflip_analysis.json")))
    c = a["original_dataset_conditioning"]
    fig, ax = plt.subplots(1, 2, figsize=(7.0, 2.3))
    sv = np.array(c["singular_values"])
    sv = np.maximum(sv, 1e-18)
    ax[0].semilogy(range(1, len(sv) + 1), sv / sv.max(), "o-", color="crimson",
                   label=f"single-trajectory set\n(rank {c['numerical_rank_of_9_columns']}/9)")
    d = np.load(os.path.join(HERE, "data", "dataset_MP.npz"), allow_pickle=True)
    F = d["feat"]
    Fa = np.hstack([F, np.ones((len(F), 1))])
    sv2 = np.linalg.svd(Fa - Fa.mean(0), compute_uv=False)
    ax[0].semilogy(range(1, len(sv2) + 1), sv2 / sv2.max(), "s--", color="tab:blue",
                   label="excited design (rank 9/9)")
    ax[0].set_xlabel("index")
    ax[0].set_ylabel("normalised singular value")
    ax[0].set_ylim(1e-18, 3)
    ax[0].legend(loc="lower left")

    j = a["constrained_refit_on_revised_dataset"]["jitter_seed_sensitivity"]
    names = {"ORIGINAL-single-trajectory": "single trajectory", "MP": "excited (MP)",
             "NMP": "excited (NMP)"}
    xs, med, lo, hi, frac = [], [], [], [], []
    for i, (k, lab) in enumerate(names.items()):
        p = j[k]["pump2"]
        xs.append(lab)
        med.append(p["coef_on_e_median"])
        lo.append(p["coef_on_e_min"]); hi.append(p["coef_on_e_max"])
        frac.append(p["wrong_sign_frac"])
    xi = np.arange(len(xs))
    ax[1].errorbar(xi, med, yerr=[np.array(med) - np.array(lo), np.array(hi) - np.array(med)],
                   fmt="o", color="crimson", capsize=3)
    ax[1].axhline(0.0, color="k", lw=0.8)
    ax[1].set_yscale("symlog", linthresh=1e-2)
    ax[1].set_xticks(xi)
    ax[1].set_xticklabels(xs, fontsize=6)
    ax[1].set_ylabel(r"fitted coefficient on $e_2$")
    # one row of labels above the panel: anchored to the axes, so they can collide
    # with neither the error bars nor the tick labels whatever the data do
    for i, f in enumerate(frac):
        ax[1].annotate(f"wrong sign, {f*100:.0f}% of seeds", (xi[i], 1.0),
                       xycoords=("data", "axes fraction"),
                       textcoords="offset points", xytext=(0, 4),
                       ha="center", va="bottom", fontsize=5)
    # the right panel's ylabel collides with the left panel's spine at the default spacing
    fig.subplots_adjust(wspace=0.30)
    save(fig, "Fig_SignFlip.pdf")


def main():
    print("generating figures ...", flush=True)
    for f, args in ((fig_tracking, ("NMP",)), (fig_tracking, ("MP",)),
                    (fig_complexity, ()), (fig_error_decomposition, ()),
                    (fig_staircase, ("NMP",)), (fig_disturbance, ("NMP",)),
                    (fig_degradation, ()), (fig_handover, ()), (fig_roa, ()),
                    (fig_signflip, ())):
        try:
            f(*args)
        except Exception as exc:
            print(f"  !! {f.__name__}{args} failed: {type(exc).__name__}: {exc}", flush=True)


if __name__ == "__main__":
    main()
